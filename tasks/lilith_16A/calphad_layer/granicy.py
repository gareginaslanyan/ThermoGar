class NetAtomnojMassy(KeyError):
    """Элемента нет в таблице атомных масс — считать нельзя, гадать тоже."""


def v_molnye_doli(sostav_mass):
    """Масс.% (или доли) -> мольные доли. Нормирует сумму сама."""
    plohie = sorted(e.upper() for e in sostav_mass
                    if e.upper() not in ATOMNYE_MASSY)
    if plohie:
        raise NetAtomnojMassy(", ".join(plohie))
    n = {e.upper(): float(w) / ATOMNYE_MASSY[e.upper()]
         for e, w in sostav_mass.items() if float(w) > 0}
    s = sum(n.values())
    if s <= 0:
        raise ValueError("состав пуст")
    return {e: v / s for e, v in n.items()}


def normirovat_mass(sostav_mass):
    """Масс.% к сумме 100. Элементы с нулём и отрицательные отбрасываются."""
    d = {e.upper(): float(w) for e, w in sostav_mass.items() if float(w) > 0}
    s = sum(d.values())
    if s <= 0:
        raise ValueError("состав пуст")
    return {e: 100.0 * w / s for e, w in d.items()}


def osnova_sostava(sostav_mass):
    """Элемент с наибольшей массовой долей."""
    d = normirovat_mass(sostav_mass)
    return max(d, key=d.get)
