import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
MANIFEST = json.loads((ROOT / "docs/guide/img/_manifest.json").read_text(encoding="utf-8"))
READINGS = {frame["image"]: frame.get("readings", {}) for frame in MANIFEST["frames"]}
STOP_NOTE = READINGS["soobshcheniya-03.png"]["stop_note"]
assert "баланс масс нарушен" not in STOP_NOTE
STOP_TIME = STOP_NOTE.split("Расчёт остановлен на ", 1)[1].split(" с ", 1)[0]  # как на экране
STOP_TIME_RU = STOP_TIME.replace(".", ",")
KINETIKA_T = 60  # results/wave21_x/zamer/zamer_kinetika.json: 60,6 с, до 5 с


def wrap(text: str, prefix: str = "", first: str | None = None, width: int = 100) -> str:
    return textwrap.fill(
        text, width=width, initial_indent=prefix if first is None else first,
        subsequent_indent=prefix, break_long_words=False, break_on_hyphens=False,
    )


rows: list[tuple[str, str, str, str, str]] = []
texts: dict[str, str] = {}


def edit(rel: str, old: str, new: str, source: str) -> None:
    text = texts.setdefault(rel, (ROOT / rel).read_text(encoding="utf-8"))
    assert text.count(old) == 1, (rel, old[:60], text.count(old))
    texts[rel] = text.replace(old, new)
    rows.append((rel, old, new, source, new))


def lines_of(rel: str, new: str) -> str:
    text = texts[rel]
    start = text.index(new)
    first = text.count("\n", 0, start) + 1
    last = first + new.count("\n")
    return f"{rel}:{first}" if first == last else f"{rel}:{first}–{last}"


