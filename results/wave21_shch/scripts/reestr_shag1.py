# г) бэклог: строка — «| BL | источник | описание | состояние |»
def bounds(bl: str) -> tuple[int, int]:
    key = f"\n| {bl} | "
    assert text.count(key) == 1, bl
    start = text.index(key) + 1
    return start, text.index("\n", start)


def set_row(bl: str, description: str | None, state: str) -> None:
    global text
    start, end = bounds(bl)
    line = text[start:end]
    assert line.endswith(" |"), line[-20:]
    cells = line[2:-2].split(" | ")
    assert len(cells) == 4, (bl, len(cells))
    if description is not None:
        cells[2] = description
    cells[3] = state
    text = text[:start] + "| " + " | ".join(cells) + " |" + text[end:]


