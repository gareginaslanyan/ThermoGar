# Номера строк задания сверяются до правок; правки — снизу вверх.
offsets = []
for line_no, old, _new in EDITS:
    assert text.count(old) == 1, old[:60]
    at = text.index(old)
    assert text.count("\n", 0, at) + 1 == line_no, (line_no, text.count("\n", 0, at) + 1)
    offsets.append(at)
for at, (_line_no, old, new) in sorted(zip(offsets, EDITS), reverse=True):
    text = text[:at] + new + text[at + len(old):]
# п. 3: пробел перед фразой убран вместе с ней, строка кончается «базы.»
assert "проверяются версии пакетов и доступные базы.\n" in text

path.write_bytes(text.encode("utf-8"))
print("ok")
