def main() -> None:
    rows = []
    for rid, (itog, ekran) in OCENKI.items():
        record = json.loads((OUT / "runs" / f"{rid}.json").read_text(encoding="utf-8"))
        changes = "; ".join(f"«{label}» {value if not isinstance(value, list) else ', '.join(value)}"
                            for _, label, value in record["changes"]) or "—"
        variant = record["variant"] + (f" ({record['step']})" if record["step"] else "")
        seconds = record.get("calc_s")
        if record.get("step1_s") is not None:
            seconds = f"{record['step1_s']} + {seconds}"
        rows.append([record["id"], record["screen"], record["base"], variant, changes,
                     seconds, itog, ekran, ", ".join(record.get("frames", []))])
    with open(OUT / "itogi.csv", "w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.writer(handle, delimiter=";")
        writer.writerow(["прогон", "экран", "база", "вариант", "что изменено",
                         "время расчёта, с", "итог", "что на экране", "кадры"])
        writer.writerows(rows)
    print(len(rows), "rows")


if __name__ == "__main__":
    main()
