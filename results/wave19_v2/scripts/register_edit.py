"""Правка tasks/REGISTER.md по шагу 7 задания 19-В2 (тексты мастера дословно)."""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
PATH = ROOT / "tasks" / "REGISTER.md"

PHRASES = (
    "Кубическая структура.", "Тетрагональная структура.", "Ромбическая структура.",
    "Моноклинная структура.", "Гексагональная структура.", "Ромбоэдрическая структура.",
    "Интерметаллидная фаза.", "Силицидная фаза.", "Газовая фаза.", "Дисперсоид.",
    "Упрочняющий дисперсоид.", "Упрочняющая фаза.", "Топологически плотноупакованная (ТПУ) фаза.",
    "Может охрупчивать сплав.", "Твёрдая и хрупкая фаза.", "Высокотемпературная модификация.",
    "Низкотемпературная модификация.", "Служебная фаза базы: только для расчёта равновесия.",
    "Служебная фаза базы: только для расчёта термодинамических свойств.",
)


def replace_once(text: str, old: str, new: str) -> str:
    assert text.count(old) == 1, old[:80]
    return text.replace(old, new)


def main() -> None:
    data = PATH.read_bytes()
    assert b"\r\n" not in data
    text = data.decode("utf-8")

    # 7а
    row_v_start = "| 19-В | `WAVE19_V_OPUS.md` |"
    start = text.index(row_v_start)
    end = text.index("\n", start)
    row = text[start:end]
    new_row = replace_once(
        row,
        "**сдано, мастер не смотрел.**",
        "**принята мастером 23.09.2026.** Расхождения 36 из 80 решены по правилам задания в пользу "
        "разметки исполнителя: у Jev ошибки класса по имени фазы (O_MN2B — оксид, MO2M1B2 — оксид, "
        "CR3MN5 — нитрид, бориды не распознаны) и «высокотемпературная модификация» без слов в тексте.",
    )
    # 7б
    new_row += (
        "\n| 19-В2 | `WAVE19_V2_OPUS.md` | `ThermoGar` / `wave19-v2` | BL-58, часть 2: описания 94 строк "
        "справочника фаз из утверждённых фраз по разметке 19-В; модуль `app/thermogar_phase_descriptions.py` | "
        "**сдано, мастер не смотрел.** Справочник 99/195/132 строк: изменились ровно 94 строки "
        "(Ni 26, Al 27, Fe 41), только столбец «Описание по-русски» — у всех до заглушка, после сборка "
        "фраз по ключам разметки; остальные 332 строки побайтно прежние; заглушка осталась у 5 строк "
        "(Ni 2, Al 0, Fe 3). Таблица 77 пар, 30 фраз (19 новых). Тест шага 2: на `70616e2` 3 passed, "
        "1 failed, 5 errors; после — 9 passed. Регрессия 2 файла: 20 passed, 0 failed. "
        "Отчёт `tasks/WAVE19_V2_REPORT.md` |"
    )
    text = text[:start] + new_row + text[end:]

    # 7в
    text = replace_once(
        text,
        "**в работе 19-В: вариант А владельца — описания собираются из утверждённых фраз по разметке; "
        "фразы утверждены 23.09.2026.**",
        "**закрыт 19-В2; ветка `wave19-v2`, в `main` не влито.** Описания 94 из 99 строк собраны из "
        "утверждённых фраз по разметке 19-В; у 5 строк (CHI_A12 в Ni и Fe, TRID в Ni и Fe, SPINEL в Fe) "
        "заглушка осталась — текст описания не называет ни структуры, ни класса.",
    )

    # 7г
    last = ("| «Неизвестный режим стали: «{значение}». Используйте «стабильный» или «метастабильный».» | "
            "«Проекты и данные» → пакетный расчёт, столбец «Ошибка» сводки (BL-56) | 19-А | да, 2026-09-23 |\n")
    rows = "".join(
        f"| «{phrase}» | «Проекты и данные» → справочник фаз, столбец «Описание по-русски» (BL-58) | 19-В2 | да, 2026-09-23 |\n"
        for phrase in PHRASES
    )
    text = replace_once(text, last, last + rows)

    # 7д
    anchor = "запись исправлена 19-Б.\n\n## Завершённые волны"
    section = (
        "запись исправлена 19-Б.\n\n"
        "### Ошибка мастера (19-В)\n\n"
        "В правиле 4 задания 19-В («класс — по химической формуле в тексте или в имени») не оговорено, "
        "что формула после символа Пирсона — прототип структурного типа (FeB, PTi3, Mn5Si3, Si4Zr5), "
        "а не состав фазы, и список приставок имени дан неполным (нет `O_`). Jev прочёл правило буквально: "
        "SITI (`oP8 Pnma FeB`) — борид, SITI3 (`PTi3`) — нитрид, O_MN2B — оксид. Исполнитель применил "
        "правило по смыслу — класс по имени фазы; итоговая разметка взята у исполнителя.\n\n"
        "## Завершённые волны"
    )
    text = replace_once(text, anchor, section)
    PATH.write_bytes(text.encode("utf-8"))


if __name__ == "__main__":
    main()
